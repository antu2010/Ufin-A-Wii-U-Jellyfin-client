#!/usr/bin/env python3
"""Regenerates src/tls_roots.cpp: the root certificates Ufin's own TLS client trusts.

Usage: python3 tools/make_roots.py [/usr/share/ca-certificates/mozilla] > src/tls_roots.cpp

The roots are Mozilla's, picked from the families that serve what Ufin talks to (GitHub's API, the Homebrew
App Store's CDN) plus the other big public CAs, so a change of certificate authority on their side does not
break the check. Refresh the list from time to time with a current ca-certificates package.
"""
import glob, os, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/ca-certificates/mozilla"
want = re.compile(r"(DigiCert|USERTrust|Sectigo|ISRG|GTS_Root|Amazon_Root|GlobalSign_Root|Baltimore|Starfield|COMODO|"
                  r"Microsoft|Go_Daddy|Entrust_Root_Certification_Authority_-_G2|Cloudflare|AAA_Certificate)", re.I)
files = sorted(f for f in glob.glob(os.path.join(src, "*.crt")) if want.search(os.path.basename(f)))
out = ['// GENERATED by tools/make_roots.py -- do not edit by hand.',
       '// Mozilla root certificates trusted by Ufin\'s own TLS client (see https_client.cpp), %d of them:' % len(files)]
for f in files:
    out.append('//   ' + os.path.basename(f)[:-4].replace('_', ' '))
out += ['', '#include "tls_roots.h"', '', 'const char* ufinTlsRootsPem() {', '    return']
for f in files:
    for line in open(f).read().strip().splitlines():
        out.append('        "%s\\n"' % line)
out.append('        ;')
out.append('}')
print("\n".join(out))
